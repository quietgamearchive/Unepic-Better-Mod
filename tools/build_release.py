"""The only supported way to build this project's release files.

    python -X utf8 tools/build_release.py build     write both zips + MANIFEST.txt
    python -X utf8 tools/build_release.py check     rebuild and compare entry hashes
    python -X utf8 tools/build_release.py verify    preflight: inputs complete,
                                                    bin/ == deployed DLLs,
                                                    no junk in the pack folders

Everything a package needs lives inside this folder; the game installation is only
read by `verify` to prove bin/ still matches what is deployed.  Never zip folders
by hand - the file list below is the definition of the release.
"""
import hashlib
import os
import sys
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REL = os.path.join(ROOT, "release")
VERSION = "1.0.1"                                  # keep in sync with MOD_TITLE in src
TOP = "Unepic_Better_Mod_v1.0.1.zip"
SRC = "Unepic_Better_Mod_v1.0.1_source_repo.zip"
MANIFEST = os.path.join(REL, "MANIFEST.txt")
GAME_MOD = r"D:\SteamLibrary\steamapps\common\Unepic\mod"   # verify only

# release archive: <arcname> -> file on disk.  README.md at the root is the user
# documentation; everything else lives under mod/ so that unzipping into the game
# folder puts a single "mod" directory next to unepic.exe.
RELEASE_ORDER = [
    ("README.md", "README.md"),
    ("img/panel.png", "img/panel.png"),
    ("mod/SDL2.dll", "bin/SDL2.dll"),
    ("mod/unepic_mod_core.dll", "bin/unepic_mod_core.dll"),
    ("mod/install.ps1", "scripts/install.ps1"),
    ("mod/uninstall.ps1", "scripts/uninstall.ps1"),
    ("mod/items.tsv", "data/items.tsv"),
    ("mod/unepic_mod.ini", "data/unepic_mod.ini"),
]
RELEASE_DICT_PREFIX = ("itemNames_", "itemDesc_", "effectName_")   # 19 + 19 + 19 = 57 files

# GitHub repository content mirrors UPLOAD_FILES in github_api_upload.py:
# README + screenshot folder + build script + source folders + the tools folder.
REPO_DIRS = ["src", "scripts", "data", "img", "tools"]
REPO_FILES = ["README.md", "build.ps1"]


def repo_map():
    m = {}
    for rel in REPO_FILES:
        m[rel] = os.path.join(ROOT, rel.replace("/", os.sep))
    for d in REPO_DIRS:
        base = os.path.join(ROOT, d)
        for dirpath, dirnames, filenames in os.walk(base):
            dirnames.sort()
            for n in sorted(filenames):
                full = os.path.join(dirpath, n)
                rel = os.path.relpath(full, ROOT).replace(os.sep, "/")
                m[rel] = full
    return m

# things that must never end up in a package
FORBIDDEN_NAMES = ["DEVELOPMENT.md", "AGENTS.md", "changelog_CN.txt", "unepic_mod.log",
                   "SDL2_orig.dll", "unepic_mod_core.c", "unepic_loader.c"]
FORBIDDEN_SUFFIX = (".pdb", ".lib", ".obj", ".exp")
FORBIDDEN_PREFIX = ("core_", "bonus", "challenges_", "logros_")


def release_map():
    m = {}
    for arc, rel in RELEASE_ORDER:
        m[arc] = os.path.join(ROOT, rel.replace("/", os.sep))
    d = os.path.join(ROOT, "data", "dict")
    for n in sorted(os.listdir(d)):
        if n.startswith(RELEASE_DICT_PREFIX) and n.endswith(".tsv"):
            m["mod/dict/" + n] = os.path.join(d, n)
    return m


def md5(path):
    return hashlib.md5(open(path, "rb").read()).hexdigest()


def sha256_bytes(b):
    return hashlib.sha256(b).hexdigest()


def build(mapping, out):
    os.makedirs(os.path.dirname(out), exist_ok=True)
    tmp = out + ".new"
    raw = 0
    with zipfile.ZipFile(tmp, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for arc in sorted(mapping):
            src = mapping[arc]
            if not os.path.isfile(src):
                sys.exit("missing " + src)
            raw += os.path.getsize(src)
            z.write(src, arc)
    os.replace(tmp, out)
    print("%-42s %2d files, raw %d, zip %d" % (os.path.basename(out), len(mapping),
                                               raw, os.path.getsize(out)))
    return raw


def entry_hashes(path):
    with zipfile.ZipFile(path) as z:
        return {i.filename: hashlib.md5(z.read(i.filename)).hexdigest() for i in z.infolist()}


def write_manifest():
    lines = ["Unepic Better Mod v%s - package manifest" % VERSION,
             "generated by tools/build_release.py; this list IS the definition of the package",
             ""]
    for label, name, mapping in (("release archive", TOP, release_map()),
                                 ("source repository archive", SRC, repo_map())):
        p = os.path.join(REL, name)
        lines.append("== %s : %s (%d entries, %d bytes)" % (label, name, len(mapping),
                                                            os.path.getsize(p)))
        if label == "release archive":
            lines.append("   sha256 %s" % sha256_bytes(open(p, "rb").read()))
        for arc in sorted(mapping):
            lines.append("   %-32s %8d  md5 %s" % (arc, os.path.getsize(mapping[arc]),
                                                   md5(mapping[arc])))
        lines.append("")
    lines.append("NEVER in the release package: " + ", ".join(FORBIDDEN_NAMES))
    lines.append("             suffixes " + ", ".join(FORBIDDEN_SUFFIX) +
                 " | prefixes " + ", ".join(FORBIDDEN_PREFIX))
    lines.append("             mod/backups/, game-root unepic_mod.ini and unepic_mod.log,")
    lines.append("             dict TSVs that are not itemNames_/itemDesc_/effectName_")
    lines.append("the GitHub repository archive mirrors UPLOAD_FILES in github_api_upload.py:")
    lines.append("             README.md, img/, build.ps1, src/, scripts/, data/, tools/build_release.py")
    lines.append("             (docs/DEVELOPMENT.md, AGENTS.md and changelog_CN.txt stay local)")
    with open(MANIFEST, "w", encoding="utf-8", newline="\r\n") as f:
        f.write("\n".join(lines) + "\n")
    print("manifest                                  %2d lines, zip %d" %
          (len(lines), os.path.getsize(MANIFEST)))


def do_build():
    missing = [arc for arc, p in release_map().items() if not os.path.isfile(p)]
    if missing:
        sys.exit("missing release inputs: " + ", ".join(missing))
    n = len([a for a in release_map() if a.startswith("mod/dict/")])
    if n != 57:
        sys.exit("expected 57 dictionaries, found %d" % n)
    build(release_map(), os.path.join(REL, TOP))
    build(repo_map(), os.path.join(REL, SRC))
    write_manifest()


def do_check():
    keep = os.path.join(REL, TOP)
    if not os.path.isfile(keep):
        sys.exit("no %s yet - run 'python -X utf8 tools/build_release.py build' first" % TOP)
    before = entry_hashes(keep)
    staging = os.path.join(REL, "_staging.zip")
    build(release_map(), staging)
    after = entry_hashes(staging)
    os.remove(staging)
    ok = before == after
    print("entries %d, content identical to the existing zip: %s" % (len(after),
                                                                     "YES" if ok else "NO"))
    sys.exit(0 if ok else 1)


def upload_files_from_config():
    """Expand UPLOAD_FILES in github_api_upload.py the same way the uploader does."""
    import ast
    cfg = os.path.join(ROOT, "github_api_upload.py")
    if not os.path.isfile(cfg):
        return None
    names = None
    for node in ast.walk(ast.parse(open(cfg, encoding="utf-8").read())):
        if isinstance(node, ast.Assign) and any(
                isinstance(t, ast.Name) and t.id == "UPLOAD_FILES" for t in node.targets):
            names = ast.literal_eval(node.value)
    if names is None:
        return None
    out = set()
    for item in names:
        p = os.path.join(ROOT, item.replace("/", os.sep))
        if os.path.isdir(p):
            for dirpath, dirnames, filenames in os.walk(p):
                for n in filenames:
                    out.add(os.path.relpath(os.path.join(dirpath, n), ROOT).replace(os.sep, "/"))
        elif os.path.isfile(p):
            out.add(item)
        else:
            out.add("MISSING:" + item)
    return out


def do_verify():
    bad = 0
    mp = release_map()
    print("release inputs: %d files, raw %d bytes" %
          (len(mp), sum(os.path.getsize(p) for p in mp.values())))
    for name in ["SDL2.dll", "unepic_mod_core.dll"]:
        b = os.path.join(ROOT, "bin", name)
        g = os.path.join(GAME_MOD, name)
        if not os.path.isfile(g):
            print("  SKIP  game copy absent: " + g)
            continue
        same = md5(b) == md5(g)
        print("  %s  bin/%s == deployed mod/%s" % ("OK  " if same else "FAIL", name, name))
        bad += 0 if same else 1
    ALLOW = {"bin": {".dll"}, "scripts": {".ps1"},
             "data": {".tsv", ".ini"}, "data/dict": {".tsv"}, "img": {".png"}}
    for folder, allow in ALLOW.items():
        d = os.path.join(ROOT, folder)
        junk = [n for n in os.listdir(d)
                if os.path.isfile(os.path.join(d, n))
                and os.path.splitext(n)[1].lower() not in allow]
        if junk:
            print("  FAIL  unexpected files in %s: %s" % (folder, junk))
            bad += 1
        else:
            print("  OK    %-10s %d file(s), nothing extra" % (folder, len(os.listdir(d))))
    hits = [arc for arc in mp
            if os.path.basename(arc) in FORBIDDEN_NAMES
            or arc.endswith(FORBIDDEN_SUFFIX)
            or os.path.basename(arc).startswith(FORBIDDEN_PREFIX)]
    if hits:
        print("  FAIL  forbidden entry in release package: " + ", ".join(sorted(hits)))
        bad += len(hits)
    else:
        print("  OK    none of the %d release entries is on the forbidden list" % len(mp))
    want = upload_files_from_config()
    if want is None:
        print("  skip  github_api_upload.py not found, cannot cross-check UPLOAD_FILES")
    else:
        have = set(repo_map())
        missing, extra = sorted(have - want), sorted(want - have)
        if missing or extra:
            print("  FAIL  repo archive and UPLOAD_FILES differ")
            for p in missing:
                print("          only in REPO_DIRS/REPO_FILES: " + p)
            for p in extra:
                print("          only in UPLOAD_FILES:         " + p)
            bad += len(missing) + len(extra)
        else:
            print("  OK    repo archive == UPLOAD_FILES (%d files)" % len(have))
    print("verify result: %s" % ("PASS" if bad == 0 else "FAIL (%d)" % bad))
    sys.exit(0 if bad == 0 else 1)


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "build"
    {"build": do_build, "check": do_check, "verify": do_verify}[cmd]()
